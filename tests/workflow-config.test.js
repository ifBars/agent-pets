    expect(workflow).toContain("git show HEAD^:packages/goose-agent-pets/package.json > /tmp/previous-goose-package.json");
    expect(workflow).toContain("git show HEAD^:packages/copilot-agent-pets/package.json > /tmp/previous-copilot-package.json");
    expect(workflow).toContain("git show HEAD^:packages/windsurf-agent-pets/package.json > /tmp/previous-windsurf-package.json");
