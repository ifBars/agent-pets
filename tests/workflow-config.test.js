    expect(workflow).toContain("git show HEAD^:packages/gemini-agent-pets/package.json > /tmp/previous-gemini-package.json");
    expect(workflow).toContain("git show HEAD^:packages/cursor-agent-pets/package.json > /tmp/previous-cursor-package.json");
