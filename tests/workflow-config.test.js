    expect(workflow).toContain('Version mismatch: package.json is ${version}, packages/gemini-agent-pets/package.json is ${gemini_version}.');
    expect(workflow).toContain('Version mismatch: package.json is ${version}, packages/cursor-agent-pets/package.json is ${cursor_version}.');
    expect(workflow).toContain('Version mismatch: package.json is ${version}, packages/aider-agent-pets/package.json is ${aider_version}.');
    expect(workflow).toContain('Version mismatch: package.json is ${version}, packages/goose-agent-pets/package.json is ${goose_version}.');
